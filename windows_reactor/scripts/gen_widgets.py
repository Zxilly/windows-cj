def check_name_collisions() -> None:
    """Cangjie classes use a single member namespace: a field and a method may
    not share a name (even with different arities). Catch this at generation
    time instead of shipping broken .cj. `children` is exempt because it is a
    method/method overload (Widget.children() vs the builder), never a field."""
    errors = []
    for w in WIDGETS:
        fields = set(fn for (fn, _, _) in w["fields"])
        methods = [sig.split("(")[0] for (sig, _) in w.get("builders", [])]
        methods += [sig.replace("func ", "").split("(")[0]
                    for (sig, _) in w.get("extra_methods", [])]
        for m in methods:
            if m in fields:
                errors.append(f"{w['name']}: builder/method '{m}' collides with field '{m}'")
    if errors:
        raise SystemExit("name collisions (field vs method):\n  " + "\n  ".join(errors))


def main():
    check_name_collisions()
    os.makedirs(WIDGETS_DIR, exist_ok=True)
    for w in WIDGETS:
        path = os.path.join(WIDGETS_DIR, WIDGET_PREFIX + snake(w["name"]) + ".cj")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(gen_widget(w))
        print("wrote", path)
    epath = os.path.join(CORE_DIR, "element.cj")
    with open(epath, "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_element())
    print("wrote", epath)
    spath = os.path.join(CORE_DIR, "widget_support.cj")
    with open(spath, "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_support())
    print("wrote", spath)


def snake(name: str) -> str:
    out = []
    for i, c in enumerate(name):
        if c.isupper() and i > 0:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


if __name__ == "__main__":
    main()
