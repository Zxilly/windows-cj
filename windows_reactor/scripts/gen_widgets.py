# ── emit guards for bindings ────────────────────────────────────────────────


def emit_binding(b) -> list[str]:
    kind = b[0]
    lines = []
    if kind == "prop":
        _, prop, valexpr, guard = b
        if guard is None:
            lines.append(f"        out.add(Binding.PropB(Prop.{prop}, {valexpr}))")
        elif guard[0] == "some":
            _, field, binder = guard
            lines.append(f"        match ({field}) {{")
            lines.append(f"            case Some({binder}) => out.add(Binding.PropB(Prop.{prop}, {valexpr}))")
            lines.append(f"            case None => ()")
            lines.append(f"        }}")
        elif guard[0] == "bool":
            _, field = guard
            lines.append(f"        if ({field}) {{ out.add(Binding.PropB(Prop.{prop}, {valexpr})) }}")
        elif guard[0] == "notbool":
            _, field = guard
            lines.append(f"        if (!{field}) {{ out.add(Binding.PropB(Prop.{prop}, {valexpr})) }}")
        elif guard[0] == "ne":
            _, field, other = guard
            lines.append(f"        if ({field} != {other}) {{ out.add(Binding.PropB(Prop.{prop}, {valexpr})) }}")
        elif guard[0] == "nonempty":
            _, field = guard
            lines.append(f"        if ({field}.size > 0) {{ out.add(Binding.PropB(Prop.{prop}, {valexpr})) }}")
        elif guard[0] == "nonemptystr":
            _, field = guard
            lines.append(f"        if ({field}.size > 0) {{ out.add(Binding.PropB(Prop.{prop}, {valexpr})) }}")
        elif guard[0] == "directbrush":
            _, field, binder = guard
            lines.append(f"        match ({field}) {{")
            lines.append(f"            case Some(Direct({binder})) => out.add(Binding.PropB(Prop.{prop}, {valexpr}))")
            lines.append(f"            case _ => ()")
            lines.append(f"        }}")
        elif guard[0] == "expanderheadertext":
            _, field, binder = guard
            lines.append(f"        match ({field}) {{")
            lines.append(f"            case Some(Text({binder})) => out.add(Binding.PropB(Prop.{prop}, {valexpr}))")
            lines.append(f"            case _ => ()")
            lines.append(f"        }}")
        else:
            raise ValueError(f"unknown guard {guard}")
    elif kind == "event":
        _, event, htype, field = b
        lines.append(f"        match ({field}) {{")
        lines.append(f"            case Some(cb) => out.add(Binding.EventB(Event.{event}, Some(EventHandler.{htype}(cb))))")
        lines.append(f"            case None => out.add(Binding.EventB(Event.{event}, None))")
        lines.append(f"        }}")
    else:
        raise ValueError(f"unknown binding kind {kind}")
    return lines


