def gen_widget(w) -> str:
    name = w["name"]
    out = [HEADER, "package windows_reactor.core\n", "import std.collection.*\n", ""]
    out.append(f"public class {name} <: Widget {{")
    out.append("    public var keyValue: ?String = None")
    out.append("    public var mods: Modifiers = Modifiers()")
    # fields
    for (fn, ft, default) in w["fields"]:
        if default is None:
            out.append(f"    public var {fn}: {ft}")
        else:
            out.append(f"    public var {fn}: {ft} = {default}")
    out.append("")
    # ctor
    ctor = w["ctor"]
    if ctor:
        params = ", ".join(f"{p}: {t}" for (p, t, _) in ctor)
        out.append(f"    public init({params}) {{")
        for (_, _, assign) in ctor:
            out.append(f"        {assign}")
        out.append("    }")
    else:
        out.append("    public init() {}")
    # extra static ctor helpers
    for (sig, body) in w.get("ctor_helpers", []):
        out.append(f"    public {sig} {{")
        for line in body.split("\n"):
            out.append(f"        {line}")
        out.append("    }")
    out.append("")
    # Widget interface
    out.append(f"    public func kind(): ControlKind {{ ControlKind.{w['kind']} }}")
    out.append("    public func key(): ?String { keyValue }")
    out.append("    public func modifiers(): Modifiers { mods }")
    out.append("")
    out.append("    public func bindings(): PropBindings {")
    out.append("        let out = ArrayList<Binding>()")
    manual = w.get("bindings_manual")
    if manual is not None:
        out.extend(manual)
    else:
        for b in w["bindings"]:
            out.extend(emit_binding(b))
    out.append("        out")
    out.append("    }")
    out.append("")
    # children
    ch = w["children"]
    if ch is not None:
        form, field = ch
        out.append("    public func children(): Children {")
        if form == "keyed":
            out.append(f"        Children.Keyed({field})")
        elif form == "single":
            out.append(f"        Children.PositionalSingle({field})")
        elif form == "tabs":
            out.append(f"        Children.Tabs({field}.toArray())")
        elif form == "pivotitems":
            out.append(f"        Children.PivotItems({field}.toArray())")
        else:
            raise ValueError(f"unknown children form {form}")
        out.append("    }")
        out.append("")
    # header element override
    he = w.get("header_emit")
    if he is not None:
        out.append("    public func headerElement(): ?Element {")
        out.append(f"        {he}")
        out.append("    }")
        out.append("")
    # pane element override
    pe = w.get("pane_emit")
    if pe is not None:
        out.append("    public func paneElement(): ?Element {")
        out.append(f"        {pe}")
        out.append("    }")
        out.append("")
    # extra class methods (e.g. NavigationView.hasSearch)
    for (sig, body) in w.get("extra_methods", []):
        out.append(f"    {sig} {{")
        for line in body.split("\n"):
            out.append(f"        {line}")
        out.append("    }")
        out.append("")
    # equivalent
    out.append("    public func equivalent(other: Widget): Bool {")
    out.append(f"        if (other.kind() != ControlKind.{w['kind']}) {{ return false }}")
    out.append("        match (other.asConcreteElement()) {")
    out.append(f"            case Some(oe) => match (oe) {{")
    out.append(f"                case {name}El(o) =>")
    out.append("                    if (!mods.equivalent(o.mods)) { return false }")
    conds = " &&\n                    ".join(emit_equiv_field(s) for s in w["equiv"])
    if conds.strip():
        out.append(f"                    {conds}")
    else:
        out.append("                    true")
    out.append("                case _ => false")
    out.append("            }")
    out.append("            case None => false")
    out.append("        }")
    out.append("    }")
    out.append("")
    # to element + as concrete element (for equivalent downcast)
    out.append(f"    public func toElement(): Element {{ Element.{name}El(this) }}")
    out.append("    public func asConcreteElement(): ?Element { Some(toElement()) }")
    out.append("")
    # common modifier builders (class This chaining)
    for (sig, body) in COMMON_MODIFIERS:
        out.append(f"    public func {sig}: This {{ {body}; this }}")
    out.append("")
    # tooltip + background-theme helper convenience
    out.append("    public func tooltip(s: String): This { mods.tooltip = Some(Tooltip.text(s)); this }")
    out.append("    public func backgroundTheme(t: ThemeRef): This { setThemeBinding(mods, Prop.Background, t); this }")
    out.append("    public func foregroundTheme(t: ThemeRef): This { setThemeBinding(mods, Prop.Foreground, t); this }")
    out.append("    public func keyOf(k: String): This { keyValue = Some(k); this }")
    out.append("")
    # widget-specific builders
    for (sig, body) in w["builders"]:
        out.append(f"    public func {sig}: This {{ {body}; this }}")
    out.append("}")
    out.append("")
    # factory
    fac = w.get("factory")
    if fac is not None:
        fname, fparams, fbody = fac
        params = ", ".join(f"{p}: {t}" for (p, t) in fparams)
        out.append(f"public func {fname}({params}): {name} {{ {fbody} }}")
        out.append("")
    # extra free-standing code (additional factories etc.)
    extra = w.get("extra")
    if extra:
        out.append(extra)
        out.append("")
    return "\n".join(out)


def gen_element() -> str:
    out = [HEADER, "package windows_reactor.core\n", "import std.collection.*\n", ""]
    out.append("// Sum type of every element kind the reconciler can mount. Widget variants")
    out.append("// each correspond to a backend control; the tail variants are composition")
    out.append("// nodes. Widget classes are reference types, so variants carry them directly")
    out.append("// (recursion is safe).")
    out.append("public enum Element {")
    for w in WIDGETS:
        out.append(f"    | {w['name']}El({w['name']})")
    out.append("    | TemplatedListEl(TemplatedListElement)")
    out.append("    | ComponentEl(ComponentElement)")
    out.append("    | ErrorBoundaryEl(ErrorBoundaryElement)")
    out.append("    | ProviderEl(ProviderElement)")
    out.append("    | GroupEl(GroupElement)")
    out.append("    | CustomEl(CustomElement)")
    out.append("    | EmptyEl")
    out.append("")
    # asWidget
    out.append("    // The Widget adapter for widget variants; None for composition variants.")
    out.append("    public func asWidget(): ?Widget {")
    out.append("        match (this) {")
    for w in WIDGETS:
        out.append(f"            case {w['name']}El(v) => Some(v)")
    out.append("            case _ => None")
    out.append("        }")
    out.append("    }")
    out.append("")
    # kindName
    out.append("    public func kindName(): String {")
    out.append("        match (this) {")
    for w in WIDGETS:
        out.append(f"            case {w['name']}El(_) => \"{w['name']}\"")
    out.append("            case TemplatedListEl(_) => \"TemplatedList\"")
    out.append("            case ComponentEl(_) => \"Component\"")
    out.append("            case ErrorBoundaryEl(_) => \"ErrorBoundary\"")
    out.append("            case ProviderEl(_) => \"Provider\"")
    out.append("            case GroupEl(_) => \"Group\"")
    out.append("            case CustomEl(c) => c.kindName()")
    out.append("            case EmptyEl => \"Empty\"")
    out.append("        }")
    out.append("    }")
    out.append("")
    # discriminant tag for kind_matches
    out.append("    public func discriminant(): Int64 {")
    out.append("        match (this) {")
    idx = 0
    for w in WIDGETS:
        out.append(f"            case {w['name']}El(_) => {idx}")
        idx += 1
    for extra in ["TemplatedListEl(_)", "ComponentEl(_)", "ErrorBoundaryEl(_)",
                  "ProviderEl(_)", "GroupEl(_)", "CustomEl(_)"]:
        out.append(f"            case {extra} => {idx}")
        idx += 1
    out.append(f"            case EmptyEl => {idx}")
    out.append("        }")
    out.append("    }")
    out.append("")
    # key
    out.append("    public func key(): ?String {")
    out.append("        match (this) {")
    for w in WIDGETS:
        out.append(f"            case {w['name']}El(v) => v.keyValue")
    out.append("            case TemplatedListEl(v) => v.key")
    out.append("            case ComponentEl(v) => v.key")
    out.append("            case ErrorBoundaryEl(v) => v.key")
    out.append("            case ProviderEl(v) => v.key")
    out.append("            case GroupEl(v) => v.key")
    out.append("            case CustomEl(v) => v.key()")
    out.append("            case EmptyEl => None")
    out.append("        }")
    out.append("    }")
    out.append("")
    # modifiers
    out.append("    public func modifiers(): ?Modifiers {")
    out.append("        match (this) {")
    for w in WIDGETS:
        out.append(f"            case {w['name']}El(v) => Some(v.mods)")
    out.append("            case TemplatedListEl(v) => Some(v.modifiers)")
    out.append("            case _ => None")
    out.append("        }")
    out.append("    }")
    out.append("")
    # kindMatches
    out.append("    public func kindMatches(other: Element): Bool {")
    out.append("        if (discriminant() != other.discriminant()) { return false }")
    out.append("        match ((this, other)) {")
    out.append("            case (CustomEl(a), CustomEl(b)) => a.customTypeId() == b.customTypeId()")
    out.append("            case _ => true")
    out.append("        }")
    out.append("    }")
    out.append("")
    # canUpdate
    out.append("    public func canUpdate(other: Element): Bool {")
    out.append("        if (!kindMatches(other)) { return false }")
    out.append("        match ((this, other)) {")
    out.append("            case (ComponentEl(a), ComponentEl(b)) => a.obj.componentTypeId() == b.obj.componentTypeId()")
    out.append("            case (CustomEl(a), CustomEl(b)) => a.customTypeId() == b.customTypeId()")
    out.append("            case _ => true")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    public func isEmpty(): Bool {")
    out.append("        match (this) { case EmptyEl => true; case _ => false }")
    out.append("    }")
    out.append("}")
    out.append("")
    # elementEquivalent free fn
    out.append("// Structural equivalence: same discriminant, then delegate to the widget's")
    out.append("// hand-written equivalent() (replaces derive(PartialEq)).")
    out.append("public func elementEquivalent(a: Element, b: Element): Bool {")
    out.append("    if (a.discriminant() != b.discriminant()) { return false }")
    out.append("    match ((a, b)) {")
    for w in WIDGETS:
        out.append(f"        case ({w['name']}El(x), {w['name']}El(y)) => x.equivalent(y)")
    out.append("        case (TemplatedListEl(x), TemplatedListEl(y)) => x.equivalent(y)")
    out.append("        case (GroupEl(x), GroupEl(y)) => optStrEq(x.key, y.key) && elementArrayEquivalent(x.children, y.children)")
    out.append("        case (EmptyEl, EmptyEl) => true")
    out.append("        // Component/ErrorBoundary/Provider/Custom equivalence is decided by the")
    out.append("        // reconciler (identity / type id), not structural equality here.")
    out.append("        case (ComponentEl(_), ComponentEl(_)) => false")
    out.append("        case (ErrorBoundaryEl(_), ErrorBoundaryEl(_)) => false")
    out.append("        case (ProviderEl(_), ProviderEl(_)) => false")
    out.append("        case (CustomEl(_), CustomEl(_)) => false")
    out.append("        case _ => false")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("public func elementArrayEquivalent(a: Array<Element>, b: Array<Element>): Bool {")
    out.append("    if (a.size != b.size) { return false }")
    out.append("    var i = 0")
    out.append("    while (i < a.size) {")
    out.append("        if (!elementEquivalent(a[i], b[i])) { return false }")
    out.append("        i++")
    out.append("    }")
    out.append("    true")
    out.append("}")
    out.append("")
    # canSkipUpdate
    out.append("// True when the reconciler can skip diffing entirely: old/new equivalent and")
    out.append("// no theme bindings needing re-resolution.")
    out.append("public func canSkipUpdate(old: Element, neu: Element): Bool {")
    out.append("    if (!elementEquivalent(old, neu)) { return false }")
    out.append("    match (neu.modifiers()) {")
    out.append("        case Some(m) => !m.hasThemeBindings()")
    out.append("        case None => true")
    out.append("    }")
    out.append("}")
    out.append("")
    # attached-prop chain helpers operate on Element (return new self)
    out.append("// Grid placement field selector for the shared setGridPlacement helper.")
    out.append("public enum GridField { | Row | Column | RowSpan | ColumnSpan }")
    out.append("")
    out.append("func setGridPlacement(mods: Modifiers, value: Int32, field: GridField): Unit {")
    out.append("    let p = match (mods.grid) { case Some(g) => g; case None => GridPlacement.default() }")
    out.append("    let np = match (field) {")
    out.append("        case Row => GridPlacement(value, p.column, p.rowSpan, p.columnSpan)")
    out.append("        case Column => GridPlacement(p.row, value, p.rowSpan, p.columnSpan)")
    out.append("        case RowSpan => GridPlacement(p.row, p.column, value, p.columnSpan)")
    out.append("        case ColumnSpan => GridPlacement(p.row, p.column, p.rowSpan, value)")
    out.append("    }")
    out.append("    mods.grid = Some(np)")
    out.append("}")
    out.append("")
    out.append("// Canvas attached-position read-modify-write for the canvas* element modifiers.")
    out.append("// Each setter passes Some for the one field it changes; the rest keep their")
    out.append("// current value (default 0 when no CanvasPosition is present yet).")
    out.append("func setCanvasPosition(mods: Modifiers, left: ?Float64, top: ?Float64, zIndex: ?Int32): Unit {")
    out.append("    let p = match (mods.canvasPosition) { case Some(c) => c; case None => CanvasPosition.default() }")
    out.append("    let nl = match (left) { case Some(v) => v; case None => p.left }")
    out.append("    let nt = match (top) { case Some(v) => v; case None => p.top }")
    out.append("    let nz = match (zIndex) { case Some(v) => v; case None => p.zIndex }")
    out.append("    mods.canvasPosition = Some(CanvasPosition(nl, nt, nz))")
    out.append("}")
    out.append("")
    out.append("func accessOf(mods: Modifiers): AccessibilityModifiers {")
    out.append("    match (mods.accessibility) {")
    out.append("        case Some(a) => a")
    out.append("        case None =>")
    out.append("            let a = AccessibilityModifiers()")
    out.append("            mods.accessibility = Some(a)")
    out.append("            a")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("func setThemeBinding(mods: Modifiers, which: Prop, t: ThemeRef): Unit {")
    out.append("    let m = match (mods.themeBindings) {")
    out.append("        case Some(x) => x")
    out.append("        case None =>")
    out.append("            let x = HashMap<Prop, ThemeRef>()")
    out.append("            mods.themeBindings = Some(x)")
    out.append("            x")
    out.append("    }")
    out.append("    m.add(which, t)")
    out.append("}")
    out.append("")
    # Lazily materialise mods.keyboardAccelerators and return the live list so
    # .keyboardAccelerator(..) can append shortcuts (mirrors accessOf for a11y).
    out.append("func accelsOf(mods: Modifiers): ArrayList<KeyboardAccelerator> {")
    out.append("    match (mods.keyboardAccelerators) {")
    out.append("        case Some(a) => a")
    out.append("        case None =>")
    out.append("            let a = ArrayList<KeyboardAccelerator>()")
    out.append("            mods.keyboardAccelerators = Some(a)")
    out.append("            a")
    out.append("    }")
    out.append("}")
    out.append("")
    # Lazily materialise mods.animations and return the live AnimationModifiers.
    out.append("func animModsOf(mods: Modifiers): AnimationModifiers {")
    out.append("    match (mods.animations) {")
    out.append("        case Some(a) => a")
    out.append("        case None =>")
    out.append("            let a = AnimationModifiers()")
    out.append("            mods.animations = Some(a)")
    out.append("            a")
    out.append("    }")
    out.append("}")
    out.append("")
    # Lazily materialise mods.animations.implicitTransitions and return it, so
    # .withOpacityTransition()/.withScaleTransition() can set individual channels.
    out.append("func implicitTransitionsOf(mods: Modifiers): ImplicitTransitions {")
    out.append("    let am = animModsOf(mods)")
    out.append("    match (am.implicitTransitions) {")
    out.append("        case Some(t) => t")
    out.append("        case None =>")
    out.append("            let t = ImplicitTransitions()")
    out.append("            am.implicitTransitions = Some(t)")
    out.append("            t")
    out.append("    }")
    out.append("}")
    out.append("")
    # ── option / callback equality helpers used by generated equivalent() ──
    cb_helpers = [
        ("optCbUnitEq", "Unit"),
        ("optCbBoolEq", "Bool"),
        ("optCbStrEq", "String"),
        ("optCbF64Eq", "Float64"),
        ("optCbI32Eq", "Int32"),
        ("optCbColorEq", "(UInt8, UInt8, UInt8, UInt8)"),
        ("optCbDateTimeEq", "ReactorDateTime"),
        ("optCbTimeSpanEq", "ReactorTimeSpan"),
        ("optCbDateTimeOptEq", "?ReactorDateTime"),
        ("optCbCdrEq", "ContentDialogResult"),
    ]
    for (fnname, payload) in cb_helpers:
        out.append(f"func {fnname}(a: ?Callback<{payload}>, b: ?Callback<{payload}>): Bool {{")
        out.append("    match ((a, b)) {")
        out.append("        case (Some(x), Some(y)) => x.sameAs(y)")
        out.append("        case (None, None) => true")
        out.append("        case _ => false")
        out.append("    }")
        out.append("}")
        out.append("")
    # scalar option-equality helpers not in util.cj
    out.append("func optExpanderHeaderEq(a: ?ExpanderHeader, b: ?ExpanderHeader): Bool {")
    out.append("    match ((a, b)) {")
    out.append("        case (Some(x), Some(y)) => x.equals(y)")
    out.append("        case (None, None) => true")
    out.append("        case _ => false")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("func optElementEquivalent(a: ?Element, b: ?Element): Bool {")
    out.append("    match ((a, b)) {")
    out.append("        case (Some(x), Some(y)) => elementEquivalent(x, y)")
