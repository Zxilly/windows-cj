"""Widget + Element code generator for the reactor core.

Single source of truth for the widget catalogue. Drives:
  * core/widget_<name>.cj — one class per widget implementing the Widget
    interface (kind/key/modifiers/bindings/children/equivalent) plus the
    common modifier builder methods (class-internal `This` chaining) and a
    `toElement()`.
  * core/element.cj — the Element enum (one variant per widget + the fixed
    non-widget composition variants) and its dispatch helpers
    (asWidget/key/kindName/kindMatches/canUpdate/modifiers/elementEquivalent/
    canSkipUpdate) plus the shared free-fn helpers (setGridPlacement etc.) and
    the option/callback equality helpers used by generated equivalent().
  * core/widget_support.cj — small value types only the widget descriptors
    need (ColorArgb, ScrollViewContentOrientation, SplitViewDisplayMode,
    ExpanderHeader, ContentDialogResult).

This run emits the full widget catalogue (P4a). The emitter understands prop
guards, event bindings (with optional adapter), single/keyed/tabs/pivotitems
children, header/pane element overrides, extra class methods, manually written
bindings bodies, and a broad set of equiv kinds.

No .sh — invoke with `uv run scripts/gen_widgets.py` or `python ...`.
"""

