    members = set(config.get("workspace", {}).get("members", []))
    if members != ACTIVE_WORKSPACE_MEMBERS:
        missing = sorted(ACTIVE_WORKSPACE_MEMBERS - members)
        extra = sorted(members - ACTIVE_WORKSPACE_MEMBERS)
