def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)
    sys.exit(1)


def check_path_exists(path: Path, kind: str) -> None:
    if not path.exists():
        fail(f"missing {kind}: {path}")


def load_toml(path: Path) -> dict:
    with path.open("rb") as f:
        return tomllib.load(f)


def expected_dependency_path(dependency: str) -> str:
    return "../" + dependency.replace("_", "-")


def load_python_string_list(path: Path, name: str) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id == name:
                value = ast.literal_eval(node.value)
                if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
                    fail(f"{path.relative_to(path.parent.parent)} {name} must be a literal string list")
                return value
    fail(f"{path} must define {name}")


def rel_posix(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def section_between(text: str, start: str, end: str, label: str) -> str:
    start_index = text.find(start)
    if start_index < 0:
        fail(f"missing {label} start marker")
    end_index = text.find(end, start_index + len(start))
    if end_index < 0:
        fail(f"missing {label} end marker")
    return text[start_index:end_index]


def require_text_before(text: str, earlier: str, later: str, message: str) -> None:
    earlier_index = text.find(earlier)
    later_index = text.find(later)
    if earlier_index < 0 or later_index < 0 or earlier_index > later_index:
        fail(message)


