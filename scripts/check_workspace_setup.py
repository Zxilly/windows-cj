def check_finalizers_do_not_block_on_locks(workspace: Path) -> None:
    finalizer_decl = re.compile(r"(?m)^[ \t]*~init\s*\(\s*\)")
    blocked_patterns = (
        "synchronized(",
        ".lock()",
        ".unlock()",
        "spawn {",
        "releaseRaw(",
        "releaseArrayRawData(",
        "freeNativeValue(",
        "LibC.free",
        "coTaskMemFree(",
        "CloseHandle(",
        "RegCloseKey(",
        "CoTaskMemFree(",
        "SysFreeString(",
        "HeapFree(",
        "WindowsDeleteString(",
        "resolveProc(",
        "closeHStringState(",
        "finalizeHStringState(",
        "closeHStringBuilderState(",
        "closeBstrState(",
        "sysFreeStringAbi(",
        "closeOwnedState(",
        "hStringFree(",
        "sysFreeString(",
        "releaseSystemHStringHandle(",
        "closeStock",
        ".free()",
        ".close()",
        "wrapper.close()",
        "reference.close()",
        ".clear()",
        "unregisterTerminalEvent(",
        "CloseThreadpoolCleanupGroupMembers(",
        "releaseBase(",
        "closeComposableActivationState(",
        "clearRoutedEventHandlerSlot(",
        "compareAndSwap(",
    )
    blocked_helper_calls = (
        re.compile(r"\brelease[A-Za-z0-9_]*NoThrow\s*\("),
        re.compile(r"\bclose[A-Za-z0-9_]*NoThrow\s*\("),
        re.compile(r"\bcloseRegistryKey[A-Za-z0-9_]*\s*\("),
        re.compile(r"\bdestroySafeArrayNoThrow\s*\("),
        re.compile(r"\breleaseOwnedComPointer\s*\("),
    )
    for source in sorted(workspace.rglob("*.cj")):
        if any(part in IGNORED_SHELL_SCRIPT_DIRS for part in source.relative_to(workspace).parts):
            continue
        text = source.read_text(encoding="utf-8")
        offset = 0
        while True:
            match = finalizer_decl.search(text, offset)
            if match is None:
                break
            start = match.start()
            brace = text.find("{", match.end())
            if brace < 0:
                fail(f"{source.relative_to(workspace)} contains malformed ~init block")
            end = matching_cj_brace_end(text, brace)
            if end is None:
                fail(f"{source.relative_to(workspace)} contains unterminated ~init block")
            end += 1
            body = text[brace:end]
            for pattern in blocked_patterns:
                if pattern in body:
                    line = text[:start].count("\n") + 1
                    fail(
                        f"{source.relative_to(workspace)}:{line} finalizers must not use "
                        f"blocking cleanup paths; found {pattern}"
                    )
            for pattern in blocked_helper_calls:
                for match in pattern.finditer(body):
                    helper = match.group(0).split("(", 1)[0].strip()
                    if helper in FINALIZER_SAFE_CLEANUP_HELPERS:
                        continue
                    line = text[:start].count("\n") + 1
                    found = re.sub(r"\s+", "", match.group(0))
                    fail(
                        f"{source.relative_to(workspace)}:{line} finalizers must not call "
                        f"native/COM cleanup helpers; found {found}"
                    )
            offset = end


def matching_cj_brace_end(text: str, open_index: int) -> int | None:
    depth = 0
    in_string = False
    escaped = False
    in_line_comment = False
    in_block_comment = False
    index = open_index
    while index < len(text):
        char = text[index]
        next_char = text[index + 1] if index + 1 < len(text) else ""
        if in_line_comment:
            if char == "\n":
                in_line_comment = False
            index += 1
            continue
        if in_block_comment:
            if char == "*" and next_char == "/":
                in_block_comment = False
                index += 2
                continue
            index += 1
            continue
        if escaped:
            escaped = False
            index += 1
            continue
        if char == "\\" and in_string:
            escaped = True
            index += 1
            continue
        if not in_string and char == "/" and next_char == "/":
            in_line_comment = True
            index += 2
            continue
        if not in_string and char == "/" and next_char == "*":
            in_block_comment = True
            index += 2
            continue
        if char == '"':
            in_string = not in_string
            index += 1
            continue
        if in_string:
            index += 1
            continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return index
        index += 1
    return None


def cj_function_body(text: str, name: str, source: Path, workspace: Path) -> str:
    match = re.search(rf"\bfunc\s+{re.escape(name)}\s*\(", text)
    if match is None:
        fail(f"{source.relative_to(workspace)} must define {name}()")
    brace = text.find("{", match.end())
    if brace < 0:
        fail(f"{source.relative_to(workspace)} contains malformed {name}() body")
    depth = 0
    end = brace
    while end < len(text):
        char = text[end]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                end += 1
                break
        end += 1
    if depth != 0:
        fail(f"{source.relative_to(workspace)} contains unterminated {name}() body")
    return text[brace:end]


