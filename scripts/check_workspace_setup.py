def iter_cj_class_blocks(text: str) -> list[tuple[int, str, str]]:
    blocks: list[tuple[int, str, str]] = []
    offset = 0
    while True:
        start = text.find("class ", offset)
        if start < 0:
            break
        brace = text.find("{", start)
        if brace < 0:
            break
        header = text[start:brace]
        depth = 0
        end = brace
        while end < len(text):
            char = text[end]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    end += 1
                    break
            end += 1
        if depth != 0:
            break
        line = text[:start].count("\n") + 1
        blocks.append((line, header, text[start:end]))
        offset = end
    return blocks


def iter_cj_function_bodies(text: str, name: str) -> list[tuple[int, str]]:
    blocks: list[tuple[int, str]] = []
    search = f"func {name}"
    offset = 0
    while True:
        start = text.find(search, offset)
        if start < 0:
            break
        line_end = text.find("\n", start)
        if line_end < 0:
            line_end = len(text)
        brace = text.find("{", start, line_end)
        if brace < 0:
            offset = line_end
            continue
        depth = 0
        end = brace
        while end < len(text):
            char = text[end]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    end += 1
                    break
            end += 1
        if depth != 0:
            break
        line = text[:start].count("\n") + 1
        blocks.append((line, text[start:end]))
        offset = end
    return blocks


def check_native_allocations_have_deterministic_owner(workspace: Path) -> None:
    source_roots = [
        workspace / "windows-core" / "src",
        workspace / "windows-implement" / "src",
        workspace / "windows-interface" / "src",
        workspace / "windows-runtime" / "src",
    ]
    for source_root in source_roots:
        if not source_root.exists():
            continue
        for source in sorted(source_root.rglob("*.cj")):
            relative = source.relative_to(workspace)
            if any(part in IGNORED_SHELL_SCRIPT_DIRS for part in relative.parts):
                continue
            if relative.as_posix() == "windows-interface/src/macros/windows_interface_macros.cj":
                continue
            text = source.read_text(encoding="utf-8")
            for line, header, body in iter_cj_class_blocks(text):
                if "allocateNativeValue" not in body and "allocateNativeArray" not in body:
                    continue
                resource_close = (
                    "Resource" in header
                    and "func close(): Unit" in body
                    and "func isClosed(): Bool" in body
                    and "freeNativeValue" in body
                )
                refcount_destroy = "func destroy" in body and "freeNativeValue" in body
                runtime_destroy_callback = "setOnDestroy" in body and "freeNativeValue" in body
                if resource_close or refcount_destroy or runtime_destroy_callback:
                    continue
                fail(
                    f"{relative}:{line} owns native allocated storage but has no deterministic "
                    "Resource.close, refcount destroy, or runtime onDestroy free path"
                )


