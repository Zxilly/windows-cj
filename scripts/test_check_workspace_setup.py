class CollectionThunkGateTests(unittest.TestCase):
    def write_runtime_source(self, workspace: Path, text: str) -> None:
        path = workspace / "windows-runtime" / "src" / "collections_runtime.cj"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def test_rejects_indexof_thunk_without_null_index_guard(self) -> None:
        with tempfile.TemporaryDirectory() as temp_dir:
            workspace = Path(temp_dir)
            self.write_runtime_source(
                workspace,
                (
                    "public func __winrtThunk_IndexOf(arg0: CPointer<Unit>, arg1: CPointer<UInt32>, result__: CPointer<Bool>): Int32 {\n"
                    "    if (result__.isNull()) { return E_POINTER.value }\n"
                    "    match (this.IndexOf(value, arg1)) { case _ => S_OK.value }\n"
                    "}\n"
                    "public func __winrtThunk_IndexOf(arg0: CPointer<Unit>, arg1: CPointer<UInt32>, result__: CPointer<Bool>): Int32 {\n"
                    "    if (result__.isNull()) { return E_POINTER.value }\n"
                    "    if (arg1.isNull()) { return E_POINTER.value }\n"
                    "    match (this.IndexOf(value, arg1)) { case _ => S_OK.value }\n"
                    "}\n"
                    "public func __winrtThunk_IndexOf(arg0: CPointer<Unit>, arg1: CPointer<UInt32>, result__: CPointer<Bool>): Int32 {\n"
                    "    if (result__.isNull()) { return E_POINTER.value }\n"
                    "    if (arg1.isNull()) { return E_POINTER.value }\n"
                    "    match (this.IndexOf(value, arg1)) { case _ => S_OK.value }\n"
                    "}\n"
                ),
            )

            stderr = io.StringIO()
            with contextlib.redirect_stderr(stderr):
                with self.assertRaises(SystemExit) as raised:
                    setup.check_collection_indexof_thunks_reject_null_index(workspace)

            self.assertEqual(raised.exception.code, 1)
            self.assertIn("IndexOf thunk must reject null index out pointer", stderr.getvalue())

    def test_accepts_indexof_thunks_with_null_index_guard(self) -> None:
        body = (
            "public func __winrtThunk_IndexOf(arg0: CPointer<Unit>, arg1: CPointer<UInt32>, result__: CPointer<Bool>): Int32 {\n"
            "    if (result__.isNull()) { return E_POINTER.value }\n"
            "    if (arg1.isNull()) { return E_POINTER.value }\n"
            "    match (this.IndexOf(value, arg1)) { case _ => S_OK.value }\n"
            "}\n"
        )
        with tempfile.TemporaryDirectory() as temp_dir:
            workspace = Path(temp_dir)
            self.write_runtime_source(workspace, body + body + body)

            setup.check_collection_indexof_thunks_reject_null_index(workspace)

    def test_accepts_indexof_thunks_with_combined_null_index_guard(self) -> None:
        body = (
            "public func __winrtThunk_IndexOf(arg0: CPointer<Unit>, arg1: CPointer<UInt32>, result__: CPointer<Bool>): Int32 {\n"
            "    if (result__.isNull() || arg1.isNull()) { return E_POINTER.value }\n"
            "    match (this.IndexOf(value, arg1)) { case _ => S_OK.value }\n"
            "}\n"
        )
        with tempfile.TemporaryDirectory() as temp_dir:
            workspace = Path(temp_dir)
            self.write_runtime_source(workspace, body + body + body)

            setup.check_collection_indexof_thunks_reject_null_index(workspace)


