                "public class Windows_Win32_System_Com_IStream <: Resource {\n"
                "    private let raw: CPointer<Unit>\n"
                "    public init(raw: CPointer<Unit>) { this.raw = raw }\n"
                "    public func asRaw(): CPointer<Unit> { raw }\n"
                "    public func close(): Unit { () }\n"
                "    public static func projectionKind(): String { return \"interface\" }\n"
